import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { App } from "./App";
import { MembersPage } from "./Members";
import { api, APIError } from "./api";
const preview = { email: "member@example.test", tenant_name: "Example team", expires_at: "2030-01-01T00:00:00Z" };
beforeEach(() => { vi.restoreAllMocks(); sessionStorage.clear(); history.replaceState(null, "", "/#reset=first"); });
afterEach(cleanup);
it("keeps a sign-in escape after a committed recovery loses its response and retry finds a used link", async () => {
    vi.spyOn(api, "previewPasswordRecovery").mockResolvedValue(preview);
    const complete = vi.spyOn(api, "completePasswordRecovery")
        .mockRejectedValueOnce(new TypeError("connection lost"))
        .mockRejectedValueOnce(new APIError(404, "not_found", "The requested resource was not found."));
    render(<App />);
    await screen.findByText("Example team · member@example.test");
    expect(screen.getByRole("link", { name: "Back to sign in" })).toHaveProperty("hash", "");
    for (const label of ["New password", "Confirm new password"]) fireEvent.change(screen.getByLabelText(label, { exact: true }), { target: { value: "new-test-password" } });
    fireEvent.click(screen.getByRole("button", { name: "Set new password" }));
    await screen.findByText(/If your password was updated but the response was lost/);
    fireEvent.click(screen.getByRole("button", { name: "Set new password" }));
    await screen.findByText("The requested resource was not found.");
    expect(screen.getByRole("link", { name: "Back to sign in" }).getAttribute("href")).toBe("/");
    expect(complete).toHaveBeenCalledTimes(2);
    expect(screen.queryByRole("heading", { name: "Your password is updated" })).toBeNull();
});
it("consumes a recovery link without logging out another browser account", async () => {
    vi.spyOn(api, "previewPasswordRecovery").mockResolvedValue(preview);
    const complete = vi.spyOn(api, "completePasswordRecovery").mockResolvedValue(undefined);
    const logout = vi.spyOn(api, "logout");
    const restore = vi.spyOn(api, "restoreSession");
    const login = vi.spyOn(api, "login");
    render(<App />);
    await screen.findByText("Example team · member@example.test");
    fireEvent.change(screen.getByLabelText("New password", { exact: true }), { target: { value: "new-test-password" } });
    fireEvent.change(screen.getByLabelText("Confirm new password", { exact: true }), { target: { value: "different-password" } });
    fireEvent.click(screen.getByRole("button", { name: "Set new password" }));
    await screen.findByText("The passwords do not match.");
    expect(complete).not.toHaveBeenCalled();
    fireEvent.change(screen.getByLabelText("Confirm new password", { exact: true }), { target: { value: "new-test-password" } });
    fireEvent.click(screen.getByRole("button", { name: "Set new password" }));
    await screen.findByRole("heading", { name: "Your password is updated" });
    expect(complete).toHaveBeenCalledWith("first", "new-test-password");
    expect(location.hash).toBe("");
    expect(logout).not.toHaveBeenCalled();
    expect(restore).not.toHaveBeenCalled();
    expect(login).not.toHaveBeenCalled();
});
it("discards old form state and late previews when the recovery token changes", async () => {
    let resolveOld: (value: typeof preview) => void = () => { };
    vi.spyOn(api, "previewPasswordRecovery").mockImplementation((token) => token === "first" ? new Promise(resolve => { resolveOld = resolve; }) : Promise.resolve({ ...preview, email: "new@example.test" }));
    render(<App />);
    act(() => { location.hash = "reset=second"; window.dispatchEvent(new HashChangeEvent("hashchange")); });
    await screen.findByText("Example team · new@example.test");
    await act(async () => resolveOld(preview));
    expect(screen.queryByText("Example team · member@example.test")).toBeNull();
    expect(screen.getByLabelText("New password", { exact: true })).toHaveProperty("value", "");
});
it("keeps recovery unavailable to tenant managers and to the administrator's own member record", async () => {
    history.replaceState(null, "", "/#/members/member/recovery");
    vi.spyOn(api, "member").mockResolvedValue({ account_id: "member", email: preview.email, status: "active", joined_at: preview.expires_at });
    const create = vi.spyOn(api, "createPasswordRecovery");
    const props = { tenant: "tenant", revision: 1, capabilities: { permissions: { "iam:member:read": true, "iam:member:manage": true } }, onChanged: vi.fn() };
    const { rerender } = render(<MembersPage {...props} systemAdmin={false} actorID="other"/>);
    await screen.findByRole("heading", { name: preview.email });
    expect(screen.queryByRole("button", { name: "Create recovery link" })).toBeNull();
    rerender(<MembersPage {...props} systemAdmin actorID="member"/>);
    expect(screen.queryByRole("button", { name: "Create recovery link" })).toBeNull();
    expect(create).not.toHaveBeenCalled();
});
it("shows the issued secret once and clears the verification password", async () => {
    history.replaceState(null, "", "/#/members/member/recovery");
    vi.spyOn(api, "member").mockResolvedValue({ account_id: "member", email: preview.email, status: "active", joined_at: preview.expires_at });
    const create = vi.spyOn(api, "createPasswordRecovery").mockResolvedValue({ id: "recovery", email: preview.email, expires_at: preview.expires_at, token: "private-secret" });
    render(<MembersPage tenant="tenant" revision={1} systemAdmin actorID="admin" capabilities={{ permissions: { "iam:member:read": true, "iam:member:manage": true } }} onChanged={vi.fn()}/>);
    fireEvent.change(await screen.findByLabelText("Your administrator password"), { target: { value: "admin-password" } });
    fireEvent.click(screen.getByRole("button", { name: "Create recovery link" }));
    await waitFor(() => expect(create).toHaveBeenCalledWith("tenant", "member", "admin-password"));
    expect(await screen.findByLabelText("Private recovery link")).toHaveProperty("value", `${location.origin}/#reset=private-secret`);
    fireEvent.click(screen.getByRole("button", { name: "Create a replacement link" }));
    expect(screen.getByLabelText("Your administrator password")).toHaveProperty("value", "");
});
